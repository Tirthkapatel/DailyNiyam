const GU_DIGITS = ['૦', '૧', '૨', '૩', '૪', '૫', '૬', '૭', '૮', '૯'];
export function num(n, lang) {
  const s = String(n);
  if (lang !== 'gu') return s;
  return s.replace(/[0-9]/g, (d) => GU_DIGITS[Number(d)]);
}
